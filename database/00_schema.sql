using ((select public.is_admin())) with check ((select public.is_admin()));

-- Payments: user sees own payment; admin manages.
drop policy if exists payments_select_own_or_admin on public.payments;
create policy payments_select_own_or_admin on public.payments for select to authenticated
using ((select public.is_admin()) or exists (select 1 from public.orders o where o.id = order_id and o.user_id = (select auth.uid())));
