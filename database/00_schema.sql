-- Profiles: users see/update themselves; admins can manage all.
drop policy if exists profiles_select_own_or_admin on public.profiles;
create policy profiles_select_own_or_admin on public.profiles for select to authenticated
using ((select auth.uid()) = id or (select public.is_admin()));

drop policy if exists profiles_update_own_or_admin on public.profiles;
create policy profiles_update_admin_only on public.profiles for update to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

-- Levels: everyone authenticated can read; admins manage.
drop policy if exists levels_select_auth on public.levels;
create policy levels_select_auth on public.levels for select to authenticated using (true);
drop policy if exists levels_admin_insert on public.levels;
create policy levels_admin_insert on public.levels for insert to authenticated with check ((select public.is_admin()));
drop policy if exists levels_admin_update on public.levels;
create policy levels_admin_update on public.levels for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists levels_admin_delete on public.levels;
create policy levels_admin_delete on public.levels for delete to authenticated using ((select public.is_admin()));

-- Products: users read active products; admins read/manage all.
drop policy if exists products_select on public.products;
create policy products_select on public.products for select to authenticated
using (active = true or (select public.is_admin()));
drop policy if exists products_admin_insert on public.products;
create policy products_admin_insert on public.products for insert to authenticated with check ((select public.is_admin()));
drop policy if exists products_admin_update on public.products;
create policy products_admin_update on public.products for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists products_admin_delete on public.products;
