-- =========================================================
-- 1) GUARANTEE PROFILE CREATION AFTER SUPABASE AUTH SIGNUP
-- =========================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_username text;
  v_name text;
begin
  v_username := lower(trim(coalesce(new.raw_user_meta_data->>'username','')));
  v_name := trim(coalesce(new.raw_user_meta_data->>'full_name',''));

  if v_username = '' then
    v_username := lower(split_part(coalesce(new.email,''),'@',1));
  end if;

  insert into public.profiles(
    id, username, full_name, role, saldo, point,
    account_status, verified, admin_level, created_at, updated_at
  )
  values(
    new.id, v_username, v_name, 'user', 0, 0,
    'active', false, 'readonly', now(), now()
  )
  on conflict (id) do update set
    full_name=case when public.profiles.full_name='' then excluded.full_name else public.profiles.full_name end,
    username=case when public.profiles.username='' then excluded.username else public.profiles.username end,
    updated_at=now();

  return new;
exception when unique_violation then
  raise exception 'Username sudah digunakan';
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

