-- 2) FRONTEND ERROR LOGGING
-- =========================================================
create table if not exists public.error_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  type text not null,
  message text not null,
  stack text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists idx_error_logs_created on public.error_logs(created_at desc);
create index if not exists idx_error_logs_user_created on public.error_logs(user_id,created_at desc);
alter table public.error_logs enable row level security;
drop policy if exists error_logs_admin_select on public.error_logs;
create policy error_logs_admin_select on public.error_logs for select to authenticated using(public.is_admin());
drop policy if exists error_logs_insert_own on public.error_logs;
create policy error_logs_insert_own on public.error_logs for insert to authenticated with check(user_id=(select auth.uid()) or user_id is null);

-- =========================================================
-- 3) SAFE ORDER ROLLBACK AFTER POST-ORDER PAYMENT FAILURE
-- =========================================================
create or replace function public.cancel_pending_order(p_order_id text)
returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare o public.orders%rowtype;
begin
  select * into o from public.orders where id=trim(p_order_id) for update;
  if not found then return false; end if;
  if o.user_id<>(select auth.uid()) and not public.is_admin_writer() then
    raise exception 'Order bukan milik user saat ini';
  end if;
  if o.status<>'pending' then return false; end if;

  update public.orders
  set status='cancelled', cancel_reason='Checkout/payment creation gagal sebelum pembayaran dibuat.', updated_at=now()
  where id=o.id and status='pending';

  insert into public.order_events(order_id,status,note,created_by)
  values(o.id,'cancelled','Order dibatalkan otomatis karena tahap pembayaran gagal.',auth.uid());
  return found;
end;
$$;
revoke all on function public.cancel_pending_order(text) from public;
grant execute on function public.cancel_pending_order(text) to authenticated;

